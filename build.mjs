import { writeFile } from 'node:fs/promises';
import { build } from 'esbuild';
import calc from '@smogon/calc';
import { Dex } from '@pkmn/sim';

const gen = calc.Generations.get(7);
const dex = Dex.mod('gen7');
const data = { species: {}, moves: {}, items: {}, natures: [...gen.natures].map(n => n.name) };
for (const species of gen.species) {
  const full = dex.species.get(species.name === 'Aegislash-Both' ? 'Aegislash' : species.name);
  data.species[calc.toID(species.name)] = {
    name: species.name,
    abilities: full.exists ? [...new Set(Object.values(full.abilities))] : Object.values(species.abilities || {}),
  };
}
for (const move of gen.moves) {
  const full = dex.moves.get(move.name);
  data.moves[calc.toID(move.name)] = {
    accuracy: full.accuracy, multihit: full.multihit, multiaccuracy: full.multiaccuracy,
    ohko: full.ohko, ignoreAbility: full.ignoreAbility, isZ: full.isZ,
  };
}
for (const item of gen.items) {
  const full = dex.items.get(item.name);
  data.items[calc.toID(item.name)] = { name: item.name, megaStone: full.megaStone };
}
await writeFile('gen7-data.mjs', '// Generated by npm run build from pinned Gen 7 data; do not edit.\nexport default ' + JSON.stringify(data) + ';\n');
await build({ entryPoints: ['damage-worker.mjs'], bundle: true, format: 'esm', target: 'es2020',
  minify: true, outfile: 'damage-worker.bundle.mjs', legalComments: 'linked' });
console.log('Built local damage worker. No npm installation or external requests are needed to serve the site.');
